package com.uniclubs.model;

public class DashboardStats {
    private int totalClubs;
    private int totalActivities;
    private int totalNotifications;

    // Getters and Setters
    public int getTotalClubs() { return totalClubs; }
    public void setTotalClubs(int totalClubs) { this.totalClubs = totalClubs; }
    public int getTotalActivities() { return totalActivities; }
    public void setTotalActivities(int totalActivities) { this.totalActivities = totalActivities; }
    public int getTotalNotifications() { return totalNotifications; }
    public void setTotalNotifications(int totalNotifications) { this.totalNotifications = totalNotifications; }
}